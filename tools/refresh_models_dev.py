#!/usr/bin/env python3
"""Refresh the embedded models.dev context-window catalog (v4.7, design 010 §18).

Fetches the stable models.dev v1 catalog (https://models.dev/api.json, MIT)
and regenerates include/mini_agent/models_dev_data.hpp: a compact TSV embedded
as a raw string literal, one row per (provider base_url, model id, context,
output). The C++ side (src/models_dev.cpp) matches config.base_url + model
against this table as the last fallback in the context-window chain.

Manual dev tool, not a quality gate. Run when the catalog should catch up
with new models:

    python3 tools/refresh_models_dev.py            # fetch + regenerate
    python3 tools/refresh_models_dev.py --input f.json  # offline re-parse
"""

import argparse
import json
import sys
import urllib.request

URL = "https://models.dev/api.json"
HEADER = "include/mini_agent/models_dev_data.hpp"
SOURCE_STAMP = "https://models.dev/api.json (MIT, anomalyco/models.dev)"


def build_rows(catalog: dict) -> list:
    rows = []
    seen = set()
    for pid, provider in catalog.items():
        base = (provider.get("api") or "").strip()
        if not base.startswith("http"):
            continue  # no wire-comparable base_url
        base = base.rstrip("/")
        for mid, model in (provider.get("models") or {}).items():
            limit = model.get("limit") or {}
            context = limit.get("context")
            if not isinstance(context, int) or context <= 0:
                continue
            output = limit.get("output") if isinstance(limit.get("output"), int) else 0
            key = (base, mid)
            if key in seen:
                continue  # first listing wins on duplicate (base, model)
            seen.add(key)
            if "\t" in mid or "\n" in mid or "\t" in base or "\n" in base:
                continue  # never trust id/url shapes to survive the TSV
            rows.append((base, mid, context, output))
    rows.sort()
    return rows


TSV_TEMPLATE = """#pragma once

// clang-format off

// Generated by tools/refresh_models_dev.py -- DO NOT EDIT.
// models.dev v1 context-window catalog, compact TSV:
//   base_url \\t model_id \\t context_tokens \\t output_tokens(0=unknown)
// Source: {source}
// Rows: {count}
namespace mini_agent {{

inline constexpr const char kModelsDevCatalogTsv[] = R"TSV({tsv})TSV";

}} // namespace mini_agent
// clang-format on
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", help="use a saved api.json instead of fetching")
    args = parser.parse_args()
    if args.input:
        with open(args.input, encoding="utf-8") as fh:
            catalog = json.load(fh)
    else:
        with urllib.request.urlopen(URL, timeout=60) as resp:
            catalog = json.load(resp)
    rows = build_rows(catalog)
    if len(rows) < 1000:
        print(f"refusing to write: only {len(rows)} rows parsed (schema drift?)", file=sys.stderr)
        return 1
    tsv = "".join(f"{base}\t{mid}\t{ctx}\t{out}\n" for base, mid, ctx, out in rows)
    text = TSV_TEMPLATE.format(source=SOURCE_STAMP, count=len(rows), tsv=tsv)
    with open(HEADER, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {HEADER}: {len(rows)} rows, {len(tsv)} bytes TSV")
    return 0


if __name__ == "__main__":
    sys.exit(main())
